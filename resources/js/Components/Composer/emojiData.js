/** Todas las entradas planas, con su categoría (para el buscador). */
export const ALL_EMOJIS = EMOJI_CATEGORIES.flatMap((c) =>
    c.items.map(([char, name, keywords]) => ({ char, name, keywords, category: c.id })),
);

const normalize = (s) => s.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');

/** Busca por nombre o palabra clave, sin distinguir mayúsculas ni tildes. */
export const searchEmojis = (query) => {
    const q = normalize(query.trim());
    if (!q) return [];
    return ALL_EMOJIS.filter((e) => normalize(`${e.name} ${e.keywords}`).includes(q));
};
