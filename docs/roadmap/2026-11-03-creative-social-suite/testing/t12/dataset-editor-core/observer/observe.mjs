import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {parseDatasetTable,datasetTableChunks,editDatasetCell,cellText,cellType,cellFromInput} from '../../../../resources/js/Studio/dataset-table.js';
const root=new URL('./',import.meta.url);
const raw=readFileSync(new URL('php-canonical.json',root),'utf8');
const table=parseDatasetTable(raw);
assert.equal(table.rows.length,13);
const same=[...datasetTableChunks(table)].join('');
assert.equal(same,raw,'PHP canonical -> lossless parse -> chunks must preserve every byte of this fixture');
assert.equal(cellText(table.rows[2].values[1]),'-0.0');
assert.equal(cellText(table.rows[3].values[1]),'9007199254740993');
assert.equal(cellText(table.rows[5].values[1]),'9223372036854775807');
assert.equal(cellType(table.rows[0].values[0]),'text');
assert.equal(cellType(table.rows[0].values[2]),'empty');
const changed=editDatasetCell(table,'r12','c_text',cellFromInput('modificado\n🎵','text'));
const roundtrip=parseDatasetTable([...datasetTableChunks(changed)].join(''));
assert.equal(roundtrip.rows[12].values[0],'modificado\n🎵');
assert.equal(table.rows[12].values[0],'=SUM(A1:A2)');
for(let i=0;i<13;i++) assert.equal(cellText(roundtrip.rows[i].values[1]),cellText(table.rows[i].values[1]));
const result={scope:'Small independent PHP64/JS fidelity observer, not UI or size-limit acceptance',rows:13,checks:22,source_sha256:createHash('sha256').update(readFileSync(new URL('../../../../resources/js/Studio/dataset-table.js',import.meta.url))).digest('hex'),canonical_sha256:createHash('sha256').update(raw).digest('hex'),status:'PASS'};
writeFileSync(new URL('result.json',root),JSON.stringify(result,null,2)+'\n');
